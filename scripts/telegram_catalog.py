def find_category_for_dialog(dialog_title: str):
    """
    Given a Telegram dialog title (e.g. '💠 BUSFAHRER/IN GRUBU' or '💠 LOKFÜHRER/IN (MAKİNİSTLİK) GRUBU'),
    matches it to the appropriate category.
    """
    clean_title = dialog_title.lower()
    # Normalize common characters
    clean_title = clean_title.replace('i̇', 'i').replace('ı', 'i').replace('ö', 'o').replace('ü', 'u').replace('ş', 's').replace('ç', 'c').replace('ğ', 'g')
    
    for item in GROUP_CATALOG:
        for kw in item["keywords"]:
            norm_kw = kw.lower().replace('i̇', 'i').replace('ı', 'i').replace('ö', 'o').replace('ü', 'u').replace('ş', 's').replace('ç', 'c').replace('ğ', 'g')
            if norm_kw in clean_title:
                return item
    return None
